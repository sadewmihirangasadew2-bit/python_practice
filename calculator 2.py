text = int(input("enter your number :"))

tax = int(input("enter your second number :"))

op = input("select your operator +,-,*,/")

if op == "+":

    print("answer =",text + tax)

elif op == "-":

    print("answer =",text - tax)

elif op == "*":

    print("answer =",text * tax)

elif op == "/":

    print("answer =",text / tax)
